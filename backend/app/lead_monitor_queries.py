def is_real_it_request(text: str | None) -> bool:
    normalized = " ".join((text or "").casefold().split())
    if not normalized:
        return False
    if any(marker in normalized for marker in PROMOTIONAL_MARKERS + NON_BUYER_MARKERS):
        return False
    return any(re.search(pattern, normalized) for pattern in EXPLICIT_REQUEST_PATTERNS)


