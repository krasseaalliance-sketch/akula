def is_real_it_request(text: str | None) -> bool:
    normalized = " ".join((text or "").casefold().split())
    if not normalized or any(marker in normalized for marker in _NON_BUYER + _PROMO_MARKERS):
        return False
    for marker in _BUYER_MARKERS:
        start = normalized.find(marker)
        if start >= 0 and any(subject in normalized[start:start + 140] for subject in _IT_SUBJECTS):
            return True
    return bool(_EXPLORATORY_DEMAND_RE.search(normalized))
